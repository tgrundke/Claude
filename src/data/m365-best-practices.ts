// Simulate random pass/fail based on a weight (higher = more likely to fail)
function simulateCheck(failWeight: number): { status: M365CheckStatus; current: string; } {
  const rand = Math.random() * 100;
  if (rand < failWeight) return { status: "fail", current: "Not configured" };
  if (rand < failWeight + 15) return { status: "warning", current: "Partially configured" };
  return { status: "pass", current: "Configured" };
}

